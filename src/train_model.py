import csv
import json
from pathlib import Path

import joblib
import numpy as np

from sklearn.ensemble import RandomForestClassifier
from sklearn.multioutput import MultiOutputClassifier
from sklearn.dummy import DummyClassifier
from sklearn.metrics import accuracy_score, precision_recall_fscore_support, hamming_loss


ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data" / "processed" / "ml"
OUTPUT_DIR = ROOT / "outputs" / "models"

FEATURES = [
    "loc",
    "cyclomatic_complexity",
    "nesting_depth",
    "maintainability_index",
]

TARGETS = [
    "target_long_method",
    "target_duplicate_code",
    "target_excessive_conditional_logic",
    "target_too_many_parameters",
    "target_deeply_nested_conditions",
    "target_high_cyclomatic_complexity",
]


def load_dataset(path):
    with path.open("r", encoding="utf-8-sig", newline="") as file:
        rows = list(csv.DictReader(file))

    X = np.array([
        [float(row[column] or 0) for column in FEATURES]
        for row in rows
    ], dtype=float)

    y = np.array([
        [int(row[column]) for column in TARGETS]
        for row in rows
    ], dtype=int)

    return X, y


def evaluate_model(name, model, X_test, y_test):
    predictions = model.predict(X_test)

    results = {}

    for index, target in enumerate(TARGETS):
        precision, recall, f1, _ = precision_recall_fscore_support(
            y_test[:, index],
            predictions[:, index],
            average="binary",
            zero_division=0,
        )

        results[target] = {
            "accuracy": round(float(accuracy_score(
                y_test[:, index], predictions[:, index]
            )), 4),
            "precision": round(float(precision), 4),
            "recall": round(float(recall), 4),
            "f1_score": round(float(f1), 4),
        }

    results["overall"] = {
        "micro_f1": round(float(precision_recall_fscore_support(
            y_test, predictions, average="micro", zero_division=0
        )[2]), 4),
        "macro_f1": round(float(precision_recall_fscore_support(
            y_test, predictions, average="macro", zero_division=0
        )[2]), 4),
        "hamming_loss": round(float(hamming_loss(
            y_test, predictions
        )), 4),
        "exact_match_accuracy": round(float(np.mean(
            np.all(y_test == predictions, axis=1)
        )), 4),
    }

    print(f"\n{name}")
    print("-" * 55)

    for target in TARGETS:
        print(
            f"{target}: "
            f"F1={results[target]['f1_score']:.4f}, "
            f"Precision={results[target]['precision']:.4f}, "
            f"Recall={results[target]['recall']:.4f}"
        )

    print("Overall:", results["overall"])

    return results


def main():
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    X_train, y_train = load_dataset(DATA_DIR / "train.csv")
    X_test, y_test = load_dataset(DATA_DIR / "test.csv")

    print("ACRR - Multi-label Code Smell Classification")
    print("=" * 55)
    print("Training samples:", len(X_train))
    print("Testing samples:", len(X_test))
    print("Features:", FEATURES)
    print("Targets:", len(TARGETS))

    baseline = MultiOutputClassifier(
        DummyClassifier(strategy="most_frequent")
    )
    baseline.fit(X_train, y_train)

    model = MultiOutputClassifier(
        RandomForestClassifier(
            n_estimators=300,
            max_depth=None,
            min_samples_leaf=2,
            class_weight="balanced",
            random_state=42,
            n_jobs=-1,
        )
    )

    print("\nTraining Random Forest...")
    model.fit(X_train, y_train)
    print("Training completed.")

    baseline_results = evaluate_model(
        "BASELINE MODEL", baseline, X_test, y_test
    )

    model_results = evaluate_model(
        "RANDOM FOREST MODEL", model, X_test, y_test
    )

    model_path = OUTPUT_DIR / "acrr_random_forest.joblib"
    report_path = OUTPUT_DIR / "model_evaluation.json"

    joblib.dump(model, model_path)

    report = {
        "project": "ACRR",
        "model": "MultiOutput Random Forest",
        "features": FEATURES,
        "targets": TARGETS,
        "training_samples": len(X_train),
        "testing_samples": len(X_test),
        "random_state": 42,
        "baseline_results": baseline_results,
        "random_forest_results": model_results,
        "interpretation": (
            "Preliminary evaluation on a file-grouped test split. "
            "Labels are generated by heuristic smell detection; "
            "results do not establish independent real-world accuracy."
        ),
    }

    report_path.write_text(
        json.dumps(report, indent=4),
        encoding="utf-8",
    )

    print("\n" + "=" * 55)
    print("MODEL TRAINING AND EVALUATION COMPLETED")
    print("Saved model:", model_path)
    print("Saved evaluation:", report_path)


if __name__ == "__main__":
    main()
